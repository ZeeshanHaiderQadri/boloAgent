_E164_RE = re.compile(r"^\+[1-9]\d{6,14}$")
_DIGITS_RE = re.compile(r"\D+")
_DIAL_BY_LENGTH = sorted(set(DIAL_CODES.values()), key=len, reverse=True)
_ISOS_BY_DIAL: dict[str, list[str]] = {}
for _code, _dial in DIAL_CODES.items():
    _ISOS_BY_DIAL.setdefault(_dial, []).append(_code)


def _name_key(value: str) -> str:
    text = unicodedata.normalize("NFKD", value or "")
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = re.sub(r"[^a-z0-9]+", " ", text.lower())
    return " ".join(text.split())


_NAME_LOOKUP: dict[str, str] = {
    _name_key(name): code for code, name in COUNTRY_NAMES.items()
}
for _alias, _code in _ALIASES.items():
    _NAME_LOOKUP.setdefault(_name_key(_alias), _code)


@dataclass(frozen=True)
class LeadPhone:
    """A lead number read as E.164, or the reason it could not be read."""

    phone_e164: str | None
    country: str | None  # ISO code used to read the number, when known
    failure: str | None  # "missing" | "country_unknown" | "unrecognized"


def normalize_country_code(value: str | None) -> str | None:
    """Return an uppercase ISO-3166 alpha-2 code, or None for anything else."""
    code = (value or "").strip().upper()
    return code if code in ISO_COUNTRY_CODES else None


def lead_country(value: str | None) -> str | None:
    """Read a lead's stored country, which may be an ISO code or a name."""
    text = (value or "").strip()
    if not text:
        return None
    return normalize_country_code(text) or _NAME_LOOKUP.get(_name_key(text))


def country_name(country_iso: str | None) -> str | None:
    code = normalize_country_code(country_iso)
    return COUNTRY_NAMES.get(code) if code else None


def dial_code(country_iso: str | None) -> str | None:
    code = normalize_country_code(country_iso)
    return DIAL_CODES.get(code) if code else None


def dial_code_for_e164(number: str | None) -> str | None:
    """Longest dialling prefix of an international number, e.g. "+1512..." → "1"."""
    text = (number or "").strip()
    if not text.startswith("+"):
        return None
    digits = _DIGITS_RE.sub("", text[1:])
    for dial in _DIAL_BY_LENGTH:
        if digits.startswith(dial):
            return dial
    return None


def country_for_e164(number: str | None) -> str | None:
    """Best display country for an international number; None when unknown."""
    dial = dial_code_for_e164(number)
    if not dial:
        return None
    preferred = PRIMARY_BY_DIAL.get(dial)
    if preferred:
        return preferred
    candidates = _ISOS_BY_DIAL.get(dial) or []
    return candidates[0] if len(candidates) == 1 else None


def is_e164(number: str | None) -> bool:
    return bool(_E164_RE.match((number or "").strip()))


def international_digits(raw: str | None) -> str | None:
    """Digits of a number the caller wrote with an international prefix."""
    text = re.sub(r"[\s\-()./]", "", raw or "")
    if text.startswith("+"):
        digits = text[1:]
    elif text.startswith("00") and len(text) > 2:
        digits = text[2:]
    else:
        return None
    if not (digits.isdigit() and 8 <= len(digits) <= 15):
        return None
    return digits


def resolve_local(raw: str | None, country_iso: str | None) -> str | None:
    """Write a national number in E.164 using one known country.

    Never invents a country: the caller must already know ``country_iso``. A
    +1 number is only accepted as a 10-digit national number with a valid area
    code, so a Tokyo "03-..." number under a US hint is refused instead of
    becoming "+103...".
    """
    code = normalize_country_code(country_iso)
    if not code:
        return None
    dial = DIAL_CODES.get(code)
    if not dial:
        return None
    digits = _DIGITS_RE.sub("", raw or "")
    if not digits:
        return None

    if dial == "1":
        if len(digits) == 11 and digits.startswith("1"):
            national = digits[1:]
        elif len(digits) == 10:
            national = digits
        else:
            return None
        if national[0] in "01":
            return None
        return "+1" + national

    if digits.startswith(dial):
        candidate = digits
    else:
        # Italy and San Marino keep the leading zero in E.164.
        national = digits if code in {"IT", "SM", "VA"} else digits.lstrip("0")
        if not national:
            return None
        candidate = dial + national
    national_length = len(candidate) - len(dial)
    if not (8 <= len(candidate) <= 15 and 6 <= national_length <= 12):
        return None
    return "+" + candidate


def resolve_lead_phone(
    raw_phone: str | None,
    stored_e164: str | None,
    lead_country_value: str | None,
    sender_country: str | None = None,
) -> LeadPhone:
    """Pick the number a click-to-chat link should open for one lead.

    The order is fixed: a number written with "+" is used unchanged, otherwise
    the lead's own country, then the default sender's country, otherwise no
    link. A stored ``phone_e164`` is only trusted when it agrees with a known
    country, because the importer used to write one under a search-wide hint.
    """
    raw = (raw_phone or "").strip()
    stored = (stored_e164 or "").strip()
    lead_iso = lead_country(lead_country_value)
    sender_iso = normalize_country_code(sender_country)

    if not raw:
        if not stored:
            return LeadPhone(None, None, "missing")
        if not is_e164(stored):
            return LeadPhone(None, None, "unrecognized")
        if lead_iso and dial_code_for_e164(stored) != DIAL_CODES.get(lead_iso):
            return LeadPhone(None, None, "unrecognized")
        return LeadPhone(stored, country_for_e164(stored), None)

    international = international_digits(raw)
    if international:
        return LeadPhone(
            "+" + international, country_for_e164("+" + international), None
        )

    hint = lead_iso or sender_iso
    if hint is None:
        return LeadPhone(None, None, "country_unknown")

    resolved = resolve_local(raw, hint)
    if resolved:
        return LeadPhone(resolved, hint, None)
    if (
        lead_iso
        and is_e164(stored)
        and dial_code_for_e164(stored) == DIAL_CODES.get(lead_iso)
    ):
        return LeadPhone(stored, lead_iso, None)
    return LeadPhone(None, hint, "unrecognized")
